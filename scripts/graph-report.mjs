// npm run graph:report — Stage 5 of the Relationships review pipeline.
//
// Writes docs/GRAPH_QUALITY.md from the pipeline's committed records: counts
// per bucket, what people decided in each bucket, the human override rate on
// AGREED items, and the error types found at every stage. It is the evidence
// for any change to the spot-check size (src/data/graph/reviewConfig.js).
// Deterministic: built only from files in the repo, so a test can check the
// committed report is current.

import fs from 'node:fs'
import path from 'node:path'
import { SPOT_CHECK_SIZE } from '../src/data/graph/reviewConfig.js'

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..')
const read = (root, f, fallback) => { try { return JSON.parse(fs.readFileSync(path.join(root, f), 'utf8')) } catch { return fallback } }

const tally = (list) => [...list.reduce((m, k) => m.set(k, (m.get(k) ?? 0) + 1), new Map())].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
const pct = (n, d) => (d ? `${((100 * n) / d).toFixed(1)}%` : '—')
const table = (head, rows) => [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n')

// Stage 1 reasons, grouped by kind rather than by the names in them.
const stage1Kind = (r) => r
  .replace(/^(from|to) "[^"]*" does not resolve to a known node$/, 'counterparty is not a node')
  .replace(/^(from|to) id "[^"]*" is not a node$/, 'counterparty id is not a node')
  .replace(/^stake [\d.]+% is not stated as a percentage in the quote$/, 'stake not stated as a percentage in the quote')
  .replace(/^weight [\d.]+ is not in the quote$/, 'weight not in the quote')
  .replace(/^quote states .* but the edge has no stake$/, 'quote states a stake the edge lacks')
  .replace(/^quote is on page \d+, not the cited page \d+$/, 'quote on a different page')
  .replace(/^type "[^"]*" is not allowed$/, 'type not allowed')
const humanKind = (r) => r
  .replace(/^the graph already has this edge.*/, 'edge already in the graph')
  .replace(/^type .* is always reviewed by a person.*/, 'type customer / supplier / joint venture')
  .replace(/^second pass confidence is (\w+)$/, 'second pass confidence $1')
  .replace(/^second pass: (type disagree|direction disagree|insufficient evidence).*/, 'second pass: $1')
  .replace(/^no second pass yet.*/, 'no second pass')

// 95% upper bound on the error rate when 0 errors are seen in n checks.
const upper95 = (n) => (n ? 1 - 0.05 ** (1 / n) : 1)

export function buildQualityReport(root = ROOT) {
  const dir = 'src/data/graph/proposals'
  const triage = read(root, `${dir}/triage.json`, { items: [], counts: {} })
  const verification = read(root, `${dir}/verification.json`, { results: {} }).results
  const secondPass = read(root, `${dir}/secondpass.json`, { results: {} }).results
  const decisions = read(root, `${dir}/decisions.json`, {})
  const approved = read(root, 'src/data/graph/approved.json', { edges: [] })

  const v1 = Object.values(verification)
  const v2 = Object.values(secondPass)
  const decided = Object.values(decisions)
  const inBucket = (b) => decided.filter((d) => d.bucket === b)
  const agreedDecided = inBucket('AGREED')
  const overrides = agreedDecided.filter((d) => d.decision === 'rejected' || d.typeFixed)
  const bulkEdges = approved.edges.filter((e) => e.review?.bulk)

  const out = []
  out.push('# Relationships graph — review quality')
  out.push('')
  out.push('Generated by `npm run graph:report` from the pipeline records in `src/data/graph/proposals/` and `approved.json`. Do not edit by hand.')
  out.push('')
  out.push(`Triage as of ${triage.generatedAt ?? '—'}. Spot-check size: ${SPOT_CHECK_SIZE} (\`src/data/graph/reviewConfig.js\`).`)
  out.push('')
  out.push('## Current queue')
  out.push('')
  out.push(table(['Bucket', 'Pending'], ['NEEDS_HUMAN', 'AGREED', 'AUTO_REJECTED'].map((b) => [b, String(triage.counts?.[b] ?? 0)])))
  out.push('')
  out.push('## Decisions by bucket')
  out.push('')
  const rows = ['NEEDS_HUMAN', 'AGREED'].map((b) => {
    const d = inBucket(b)
    return [b, String(d.filter((x) => x.decision === 'approved' && !x.typeFixed).length), String(d.filter((x) => x.typeFixed).length), String(d.filter((x) => x.decision === 'rejected').length)]
  })
  const unbucketed = decided.filter((d) => !d.bucket)
  if (unbucketed.length) rows.push(['before the pipeline', String(unbucketed.filter((x) => x.decision === 'approved').length), '0', String(unbucketed.filter((x) => x.decision === 'rejected').length)])
  out.push(table(['Bucket at decision', 'Approved as proposed', 'Type fixed, then approved', 'Rejected'], rows))
  out.push('')
  out.push(`Bulk approvals ("approve all agreed"): ${bulkEdges.length} edge${bulkEdges.length === 1 ? '' : 's'} in ${new Set(bulkEdges.map((e) => e.review.approvedAt)).size} batch${new Set(bulkEdges.map((e) => e.review.approvedAt)).size === 1 ? '' : 'es'}.`)
  out.push('')
  out.push('## Human override rate on AGREED')
  out.push('')
  out.push('An override is an AGREED item a person rejected or approved with a different type.')
  out.push('')
  if (!agreedDecided.length) {
    out.push('No AGREED item has been decided yet, so there is no evidence for changing the spot-check size.')
  } else {
    out.push(`${overrides.length} of ${agreedDecided.length} decided AGREED items overridden (${pct(overrides.length, agreedDecided.length)}).`)
    if (!overrides.length) out.push(`With none overridden in ${agreedDecided.length}, the true override rate is below ${(100 * upper95(agreedDecided.length)).toFixed(1)}% at 95% confidence.`)
  }
  out.push('')
  out.push('## Error types found')
  out.push('')
  out.push(`### Stage 1 — deterministic checks (${v1.filter((r) => !r.ok).length} of ${v1.length} proposals failed)`)
  out.push('')
  const s1 = tally(v1.flatMap((r) => [...new Set(r.reasons.map(stage1Kind))]))
  out.push(s1.length ? table(['Reason', 'Proposals'], s1.map(([k, n]) => [k, String(n)])) : 'None.')
  out.push('')
  out.push(`Quote match: ${v1.filter((r) => r.match?.result === 'verified').length} verified on the cited page, ${v1.filter((r) => r.match?.result === 'wrong_page').length} on another page, ${v1.filter((r) => r.match?.result === 'not_found').length} not found.`)
  out.push('')
  out.push(`### Stage 2 — second pass (${v2.length} reading${v2.length === 1 ? '' : 's'})`)
  out.push('')
  const s2 = tally(v2.map((r) => `${r.comparison?.outcome ?? 'none'} · ${r.verdict?.confidence ?? 'no verdict'} confidence`))
  out.push(s2.length ? table(['Outcome', 'Proposals'], s2.map(([k, n]) => [k.replace(/_/g, ' '), String(n)])) : 'None.')
  const unusable = tally(v2.flatMap((r) => [...new Set(r.problems ?? [])]))
  if (unusable.length) { out.push(''); out.push(table(['Unusable reply', 'Proposals'], unusable.map(([k, n]) => [k, String(n)]))) }
  out.push('')
  out.push('### Stage 3 — why items need a person')
  out.push('')
  const s3 = tally(triage.items.filter((i) => i.bucket === 'NEEDS_HUMAN').flatMap((i) => [...new Set(i.reasons.map(humanKind))]))
  out.push(s3.length ? table(['Reason', 'Proposals'], s3.map(([k, n]) => [k, String(n)])) : 'None.')
  out.push('')
  out.push('### Human corrections')
  out.push('')
  const fixes = tally(decided.filter((d) => d.typeFixed).map((d) => `${d.typeFixed.from} → ${d.typeFixed.to}`))
  out.push(fixes.length ? table(['Type fixed', 'Times'], fixes.map(([k, n]) => [k, String(n)])) : 'No type fixes yet.')
  out.push('')
  const why = tally(decided.filter((d) => d.decision === 'rejected').map((d) => d.reason || '(no reason given)'))
  out.push(why.length ? table(['Rejection reason', 'Times'], why.map(([k, n]) => [k, String(n)])) : 'No rejections yet.')
  out.push('')
  return out.join('\n')
}

if (import.meta.url === `file://${process.argv[1]}`) {
  fs.writeFileSync(path.join(ROOT, 'docs/GRAPH_QUALITY.md'), buildQualityReport())
  console.log('wrote docs/GRAPH_QUALITY.md')
}
