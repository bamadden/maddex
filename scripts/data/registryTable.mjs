// The dataset table in docs/DATA_PLATFORM.md and src/data/registryHealth.js,
// generated from the registry so neither can drift from it
// (tests/registry.test.mjs compares them).
//   npm run data:docs   rewrites both
import { DATASETS, isManual } from '../../src/data/registry.js'

const cell = (s) => String(s ?? '—').replace(/\|/g, '\\|')
export function registryTable() {
  const head = '| Dataset | Class | Source | Fetch | Cadence | Max age | Modules |\n|---|---|---|---|---|---|---|'
  const rows = DATASETS.map((e) => `| \`${e.id}\` ${cell(e.what)} | ${e.cls} | ${cell(e.source.name)} | ${e.fetch.method}${e.fetch.verify ? `, checked by \`${e.fetch.verify}\`` : ''} | ${cell(e.cadence)} | ${e.maxAgeDays} days | ${e.modules.join(', ')} |`)
  return [head, ...rows].join('\n')
}

// What is checked by hand, when it was checked, and when it next must be:
// the check date plus the maximum age. The build fails on that date.
export async function manualTable() {
  const { datasetDates } = await import('./registryDates.mjs')
  const dates = await datasetDates()
  const add = (iso, days) => new Date(Date.parse(`${iso}T00:00:00Z`) + days * 86_400_000).toISOString().slice(0, 10)
  const rows = DATASETS.filter(isManual)
    .map((e) => ({ e, checked: dates[e.id], due: dates[e.id] ? add(dates[e.id], e.maxAgeDays) : null }))
    .sort((a, b) => (a.due ?? '').localeCompare(b.due ?? ''))
    .map(({ e, checked, due }) => `| \`${e.id}\` ${cell(e.what)} | ${cell(e.source.name)} | ${checked ?? 'not dated'} | ${e.maxAgeDays} days | ${due ?? '—'} | ${e.manualHold ? `Held until ${e.manualHold.until}: ${cell(e.manualHold.reason)}` : '—'} |`)
  return ['| Dataset | Source | Last checked | Max age | Next check due | Note |', '|---|---|---|---|---|---|', ...rows].join('\n')
}
export const MANUAL_START = '<!-- manual:start (generated by npm run data:docs; do not edit by hand) -->'
export const MANUAL_END = '<!-- manual:end -->'

export const START = '<!-- registry:start (generated by npm run data:docs; do not edit by hand) -->'
export const END = '<!-- registry:end -->'

if (import.meta.url === `file://${process.argv[1]}`) {
  const fs = await import('node:fs')
  const file = new URL('../../docs/DATA_PLATFORM.md', import.meta.url)
  const doc = fs.readFileSync(file, 'utf8')
  const a = doc.indexOf(START), b = doc.indexOf(END)
  if (a < 0 || b < 0) throw new Error('docs/DATA_PLATFORM.md has no registry markers')
  let out = `${doc.slice(0, a + START.length)}\n${registryTable()}\n${doc.slice(b)}`
  const m = out.indexOf(MANUAL_START), n = out.indexOf(MANUAL_END)
  if (m < 0 || n < 0) throw new Error('docs/DATA_PLATFORM.md has no manual-data markers')
  out = `${out.slice(0, m + MANUAL_START.length)}\n${await manualTable()}\n${out.slice(n)}`
  fs.writeFileSync(file, out)
  const { healthSource } = await import('./registryDates.mjs')
  fs.writeFileSync(new URL('../../src/data/registryHealth.js', import.meta.url), await healthSource())
  console.log(`Wrote ${DATASETS.length} datasets to docs/DATA_PLATFORM.md and src/data/registryHealth.js`)
}
