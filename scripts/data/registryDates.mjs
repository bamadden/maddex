// Each dataset's as-of date, read from its own file the way the registry test
// reads it: a dated constant, the oldest row of a dated table, or a
// verifiedConstants group's lastVerified (the oldest, for a group dated item
// by item). Used to generate src/data/registryHealth.js.
import fs from 'node:fs'
import { DATASETS } from '../../src/data/registry.js'
import { VERIFIED_CONSTANTS } from '../../src/data/verifiedConstants.js'

const root = new URL('../../', import.meta.url)
const oldest = (dates) => (dates.some((d) => d == null) ? null : dates.filter(Boolean).sort()[0] ?? null)

export async function datasetDates() {
  const out = {}
  for (const e of DATASETS) {
    const a = e.asOf
    if (!a) { out[e.id] = null; continue }
    if (a.vc) {
      const g = VERIFIED_CONSTANTS[a.vc]
      out[e.id] = g.lastVerified ?? oldest(Object.values(g).filter((v) => v?.lastVerified).map((v) => v.lastVerified))
    } else if (a.rows) {
      const rows = (await import(new URL(a.file, root)))[a.rows]
      out[e.id] = oldest(Array.isArray(rows) ? rows.map((x) => x[a.field] ?? null) : Object.values(rows).map((v) => (a.field ? v?.[a.field] : v) ?? null))
    } else {
      const m = fs.readFileSync(new URL(a.file, root), 'utf8').match(new RegExp(`\\b${a.date}\\s*=\\s*(?:'(\\d{4}-\\d{2}-\\d{2})'|null)`))
      out[e.id] = m?.[1] ?? null
    }
  }
  return out
}

export async function healthSource() {
  const dates = await datasetDates()
  const rows = DATASETS.map((e) => `  { id: '${e.id}', modules: ${JSON.stringify(e.modules).replace(/"/g, "'").replace(/,/g, ', ')}, asOf: ${dates[e.id] ? `'${dates[e.id]}'` : 'null'}, maxAgeDays: ${e.maxAgeDays}, cls: '${e.cls}' },`)
  return `// Generated by npm run data:docs from src/data/registry.js; do not edit.
// The small part of the registry the module headers need to show data health
// without loading the registry itself: each dataset's modules, as-of date,
// maximum age and class. tests/registry.test.mjs fails when it is out of date.
export const HEALTH = [
${rows.join('\n')}
]
`
}
