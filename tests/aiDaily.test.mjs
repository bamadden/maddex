// The shared daily MaddenAI endpoint and its prompts — no network: the guard
// would refuse any model call, and these tests make none.

import { test } from 'node:test'
import assert from 'node:assert/strict'
import { DAILY_KINDS, sydneyDay, secondsToSydneyMidnight } from '../src/services/aiDaily.js'
import handler, { createHandler, cronAuthorised } from '../api/ai-daily.js'

function fakeRes() {
  const r = { statusCode: null, headers: {}, body: null }
  r.status = (c) => { r.statusCode = c; return r }
  r.setHeader = (k, v) => { r.headers[k.toLowerCase()] = v; return r }
  r.json = (b) => { r.body = b; return r }
  return r
}

test('every shared kind builds its prompt offline, with no reader input', () => {
  for (const [kind, spec] of Object.entries(DAILY_KINDS)) {
    const { system, user } = spec.build({ headlines: ['RBA holds', 'Iron ore falls'] })
    assert.ok(system.length > 20 && user.length > 20, kind)
    assert.ok(spec.maxTokens > 0 && typeof spec.parse === 'function', kind)
  }
  assert.match(DAILY_KINDS.policy_bias.build().user, /- rba: RBA/)
})

test('Sydney day and cache lifetime', () => {
  assert.equal(sydneyDay(new Date('2026-10-31T13:30:00Z')), '2026-11-01') // 00:30 AEDT
  assert.equal(secondsToSydneyMidnight(new Date('2026-10-31T12:59:00Z')), 60) // 23:59 AEDT → floor 60
  const s = secondsToSydneyMidnight(new Date('2026-10-31T01:00:00Z')) // 12:00 AEDT
  assert.equal(s, 12 * 3600)
})

test('the endpoint refuses anything but ?kind=<known>&day=<today>, before any model call', async () => {
  const today = sydneyDay()
  for (const url of [
    `/api/ai-daily?kind=bogus&day=${today}`,
    '/api/ai-daily?kind=sentiment&day=2020-01-01',
    `/api/ai-daily?kind=sentiment&day=${today}&bust=1`,
    '/api/ai-daily',
  ]) {
    const res = fakeRes()
    await handler({ method: 'GET', url }, res)
    assert.equal(res.statusCode, 400, url)
    assert.equal(res.headers['cache-control'], 'no-store', url)
  }
  const post = fakeRes()
  await handler({ method: 'POST', url: `/api/ai-daily?kind=sentiment&day=${today}` }, post)
  assert.equal(post.statusCode, 405)
})

test('a view never generates: without a key, or without a stored reply, it answers "not generated" and calls no model', async () => {
  const saved = process.env.ANTHROPIC_API_KEY
  delete process.env.ANTHROPIC_API_KEY
  try {
    const res = fakeRes()
    await handler({ method: 'GET', url: `/api/ai-daily?kind=macro-themes&day=${sydneyDay()}` }, res)
    assert.equal(res.statusCode, 200)
    assert.equal(res.body.status, 'not_generated')
    assert.match(res.headers['cache-control'], /s-maxage=300/)
  } finally { if (saved) process.env.ANTHROPIC_API_KEY = saved }
  assert.equal(globalThis.__networkGuard.attempts.length, 0)
})

// Ben's decision, 26 Nov 2026: the shared daily content is generated by a
// scheduled job at a fixed time, never by a view; one per type per day.
function fakeDb(rows = []) {
  const calls = []
  const db = async (path, init = {}) => {
    calls.push({ path, method: init.method ?? 'GET' })
    if ((init.method ?? 'GET') === 'POST') { rows.push(JSON.parse(init.body)); return { ok: true, json: async () => ({}) } }
    const purpose = decodeURIComponent(/purpose=eq\.([^&]+)/.exec(path)?.[1] ?? '')
    const day = /input_data_date=eq\.([^&]+)/.exec(path)?.[1]
    const hit = rows.filter((r) => r.purpose === purpose && r.input_data_date === day).map((r) => ({ output_text: r.output_text, created_at: '2026-11-26T19:00:05Z', model: r.model }))
    return { ok: true, json: async () => hit.slice(-1) }
  }
  return { db, rows, calls }
}
const NOW = new Date('2026-11-26T20:00:00Z') // 07:00 27 Nov Sydney
const DAY = sydneyDay(NOW)

test('a view reads today\'s stored reply, re-checked by the advice guard, and caches it to Sydney midnight', async () => {
  const { db, rows } = fakeDb([{ purpose: 'daily:macro_regime', input_data_date: DAY, output_text: JSON.stringify({ regime: 'NEUTRAL', description: 'Steady.' }), model: 'm' }])
  const fetchImpl = async () => { throw new Error('a view must not fetch anything') }
  const h = createHandler({ env: { ANTHROPIC_API_KEY: 'k' }, dbFor: () => db, fetchImpl, now: () => NOW })
  const res = fakeRes()
  await h({ method: 'GET', url: `/api/ai-daily?kind=macro_regime&day=${DAY}` }, res)
  assert.equal(res.statusCode, 200)
  assert.equal(res.body.generatedAt, '2026-11-26T19:00:05Z')
  assert.equal(res.body.data.regime, 'NEUTRAL')
  assert.match(res.headers['cache-control'], /s-maxage=\d+/)
  assert.equal(rows.length, 1, 'nothing written by a view')
})

test('the daily job runs only for the cron: CRON_SECRET when set, else Vercel\'s cron agent', () => {
  assert.equal(cronAuthorised({ 'user-agent': 'vercel-cron/1.0' }, {}), true)
  assert.equal(cronAuthorised({ 'user-agent': 'Mozilla/5.0' }, {}), false)
  assert.equal(cronAuthorised({ 'user-agent': 'vercel-cron/1.0' }, { CRON_SECRET: 's3' }), false, 'with a secret the agent alone is not enough')
  assert.equal(cronAuthorised({ authorization: 'Bearer s3' }, { CRON_SECRET: 's3' }), true)
})

test('the job generates each type once a day; a second run, or a stray trigger, generates nothing', async () => {
  // Every type but macro_regime is already stored today.
  const { db, rows } = fakeDb(Object.keys(DAILY_KINDS).filter((k) => k !== 'macro_regime').map((k) => ({ purpose: `daily:${k}`, input_data_date: DAY, output_text: k === 'sentiment' ? '{"score":50}' : '{"themes":[{"title":"Rates"}],"implications":{}}', model: 'm' })))
  let modelCalls = 0
  const fetchImpl = async (url) => {
    if (/anthropic\.com/.test(url)) { modelCalls++; return { ok: true, json: async () => ({ stop_reason: 'end_turn', usage: {}, content: [{ type: 'text', text: '{"regime":"NEUTRAL"}' }] }) } }
    throw new Error(`unexpected fetch ${url}`)
  }
  const h = createHandler({ env: { ANTHROPIC_API_KEY: 'k' }, dbFor: () => db, fetchImpl, now: () => NOW })
  const denied = fakeRes()
  await h({ method: 'GET', url: '/api/ai-daily?generate=all', headers: { 'user-agent': 'Mozilla/5.0' } }, denied)
  assert.equal(denied.statusCode, 401)
  assert.equal(modelCalls, 0)
  const run = fakeRes()
  await h({ method: 'GET', url: '/api/ai-daily?generate=all', headers: { 'user-agent': 'vercel-cron/1.0' } }, run)
  assert.equal(run.statusCode, 200)
  assert.equal(run.body.results.macro_regime, 'generated')
  assert.equal(run.body.results.sentiment, 'already generated today')
  assert.equal(modelCalls, 1)
  const again = fakeRes()
  await h({ method: 'GET', url: '/api/ai-daily?generate=all', headers: { 'user-agent': 'vercel-cron/1.0' } }, again)
  assert.ok(Object.values(again.body.results).every((r) => r === 'already generated today'))
  assert.equal(modelCalls, 1, 'one generation per type per day')
  assert.equal(rows.filter((r) => r.purpose === 'daily:macro_regime').length, 1)
})

test('the schedule is in vercel.json, and the view path cannot reach the generator', async () => {
  const fs = (await import('node:fs')).default
  const vercel = JSON.parse(fs.readFileSync('vercel.json', 'utf8'))
  assert.deepEqual(vercel.crons, [{ path: '/api/ai-daily?generate=all', schedule: '0 19 * * *' }])
  const src = fs.readFileSync('api/ai-daily.js', 'utf8')
  const view = src.slice(src.indexOf("// ── A reader's view: read only ──"))
  assert.doesNotMatch(view, /generate\(/)
  const client = fs.readFileSync('src/services/aiDailyClient.js', 'utf8')
  assert.doesNotMatch(client, /generate=/)
  assert.doesNotMatch(client, /stale/, 'yesterday\'s copy is not shown in place of today\'s')
})

